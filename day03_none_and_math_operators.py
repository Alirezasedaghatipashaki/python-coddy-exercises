# --- Exercise 1: The None Keyword (Absence of Value) ---
nothing = None
print(f'nothing = {nothing}')


# --- Exercise 2: Multiple Variable Types (Int, Float, String) ---
k = 88
PI = 3.14
name = "Bob"

print(f"k = {k}")
print(f"PI = {PI}")
print(f"name = {name}")


# --- Exercise 3: Float Division ---
a = 5.2
b = 2.6
c = a / b

print(f"a = {a}, b = {b}, c = {c}")


# --- Exercise 4: Float Multiplication ---
x = 12.5
y = 3.5
z = x * y

print(f"x = {x}, y = {y}, z = {z}")
